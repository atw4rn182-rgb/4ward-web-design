export function translatePhrase(text) {
  if (lookup.has(text)) return lookup.get(text);
  const recommended = text.match(/^Recommended (.+)$/);
  if (recommended) {
    const name = lookup.get(recommended[1]) || recommended[1];
    return `Recomendado: ${name}`;
  }
  for (const [pattern, template] of PATTERNS) {
    if (pattern.test(text)) return text.replace(pattern, template);
  }
  return null;
}

export function translateLong(text) {
  let out = String(text || "");
  out = out.replace(/Tier Finder recommendation: (tier\d)\./g, "Recomendación del buscador de nivel: $1.");
  const keys = [...lookup.keys()].filter((key) => key.length >= 24).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    const spanish = lookup.get(key);
    if (spanish && out.includes(key)) out = out.split(key).join(spanish);
  }
  return out;
}
